-- 0034：镜头可以引用到"哪一套形态"（本轮任务书 §6.4／§11.1 点名的那寸空白）
--
-- 为什么非加这一列不可（先证明现有结构装不下，再动手）：
--   ① `shot.asset_ids` 是整数 JSON 数组，删除保护、引用计数、指纹三处都用
--      `json_each(s.asset_ids)` 按 `j.value = a.id` 比。把 "57:12" 这种复合串塞进
--      同一个数组，这三处会一起变成"看不见那条引用"——资产被删时保护失效，
--      那是数据损坏，不是省事。
--   ② 建一张 `shot_variant_ref` 中间表？只有"一镜挂几个形态"这一个用途，
--      而现有 `asset_ids`／`aliases`／`ref_images` 全是 JSON 列的既有写法；
--      为一个同构需求单开一张表，等于给同一件事两个家。
--   ③ 加一列 `variant_ids`（JSON 整数数组）跟 `asset_ids` 同构：现有那三处
--      一条 SQL 都不用改，形态的引用是**加进来**的一层，不是替换。
--
-- 兼容底线（测试里钉住了）：老镜头不回填，读不到就是空清单；
-- 已提交作业的 `source_version` 是提交那一刻冻住的字符串，本列改了也不会
-- 回头改写它——只是"这一镜现在的指纹"变了，于是旧产物被如实标成「源已变」。
--
-- 归属规则在服务层判（`routers/content._checked_variant_ids`），不写 CHECK：
-- 形态的父资产必须同时出现在 `asset_ids` 里，那是跨列跨表的约束，
-- SQLite 的 CHECK 做不到；写进 DDL 只能靠触发器，为一个校验养触发器不值。
-- 好处是"删这条资产会不会留下悬空的形态引用"这个问题自动成立：
-- 父资产没被引用就不算这条镜头在用这个形态，删除保护走 asset_ids 那一套即可。
ALTER TABLE shot ADD COLUMN variant_ids TEXT NOT NULL DEFAULT '[]';
