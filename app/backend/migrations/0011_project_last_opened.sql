-- 项目加"最后打开时间"。
--
-- 为什么要有它：项目中心原来按 id 倒序排，也就是"最新建的排最前"。
-- 但天天在几部剧之间来回跳的时候，"我最近在哪"和"哪个最新"是两回事。
-- 可灵团队空间、剪映云空间、waoowaoo 的项目列表都改用最后打开/最后访问排序，
-- 这条是它们共同的做法。
--
-- 为什么允许 NULL：存量项目没有打开记录。排序时把 NULL 单独当作一组排到最后
-- （见 repositories/projects.py 的 _ORDER），而不是回填一个假时间——
-- 回填成 created_at 会让"从没打开过"和"很久前打开过"混在一起，看不出来。
--
-- 归档不另开一列：project.status 从建库第一天就在，值恒为 'active' 且没有任何
-- 端点写过它（v0.52 盘点发现的死字段）。这次就把它用起来，取值 active|archived。
-- 不加 CHECK 约束：加约束要重建整张表，而状态集合到三期（审核）还会扩，
-- 白名单放在应用层 routers/projects.py 里改起来轻。
ALTER TABLE project ADD COLUMN last_opened_at TEXT;
